"""The release's version: what the tag names, the crates carry and the installers probe.

`runtime/build.sh` stages upstream's workspace at upstream's crate version
(0.8.6 at the current pin) and `caelza --version` reports it. A Caelza release
is named by its tag (v0.1.0 → caelza-0.1.0-<target>.tar.gz), and both
installers refuse a binary whose version is not the release's, so a release
build stamps the tag's version into Cargo.toml and Cargo.lock
(runtime/lib/stamp_version.py) before cargo runs. These tests pin the rule,
the rewrite on a small workspace shaped like upstream's, the pipeline's wiring
and the installers' side of the contract.
"""
from __future__ import annotations

import difflib
import importlib.util
import re
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

from caelza_body import runtime_guard as rg

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "runtime" / "lib" / "stamp_version.py"
UP = "0.8.6"
TARGET = "aarch64-linux-android"


def _load():
    spec = importlib.util.spec_from_file_location("stamp_version", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


sv = _load()


# --- a workspace shaped like upstream's -----------------------------------------

MANIFEST = f'''\
[workspace]
members = [".", "crates/caelza-api", "crates/caelza-config", "crates/caelza-plugins/tests/fixtures/tool-fixture"]
exclude = ["vendor/crossterm-0.29.0"]
resolver = "2"

[workspace.package]
version = "{UP}"
edition = "2024"
license = "MIT OR Apache-2.0"

[workspace.dependencies]
caelza-api = {{ path = "crates/caelza-api", version = "{UP}" }}
caelza-config = {{ path = "crates/caelza-config", version = "{UP}", default-features = false }}
rand = "{UP}"
crossbeam-deque = {{ version = "{UP}", default-features = false }}
serde = {{ version = "1.0.200", features = ["derive"] }}

[package]
name = "caelza"
version.workspace = true
edition.workspace = true

[dependencies]
caelza-api = {{ workspace = true }}
rand = {{ workspace = true }}
'''

MEMBER = '''\
[package]
name = "{name}"
version.workspace = true
edition.workspace = true
'''

# Path packages carry no `source`; the one with no dependencies ends at a blank line.
LOCK = f'''\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "caelza"
version = "{UP}"
dependencies = [
 "caelza-api",
 "rand",
]

[[package]]
name = "caelza-api"
version = "{UP}"

[[package]]
name = "caelza-config"
version = "{UP}"
dependencies = [
 "serde",
]

[[package]]
name = "crossbeam-deque"
version = "{UP}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "9dd111b7b7f7d55b72c0a6ae361660ee5853c9af73f70c3c2ef6858b950e2e51"

[[package]]
name = "crossterm"
version = "0.29.0"

[[package]]
name = "rand"
version = "{UP}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "34af8d1a0e25924bc5b7c43c079c942339d8f0a8b57c39049bef581b46327404"
dependencies = [
 "rand_core",
]

[[package]]
name = "rand_core"
version = "0.6.4"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "ec0be4795e2f6a28069bec0b5ff3e2ac9bafc99e6a9a7dc3547996c5c816922c"

[[package]]
name = "tool-fixture"
version = "0.0.0"
'''


def make_tree(root: Path) -> Path:
    tree = root / "src"
    for d in ("crates/caelza-api", "crates/caelza-config", "crates/caelza-plugins/tests/fixtures/tool-fixture",
              "vendor/crossterm-0.29.0", "target/debug"):
        (tree / d).mkdir(parents=True)
    (tree / "Cargo.toml").write_text(MANIFEST)
    (tree / "Cargo.lock").write_text(LOCK)
    for name in ("caelza-api", "caelza-config"):
        (tree / "crates" / name / "Cargo.toml").write_text(MEMBER.format(name=name))
    (tree / "crates/caelza-plugins/tests/fixtures/tool-fixture/Cargo.toml").write_text(
        '[package]\nname = "tool-fixture"\nversion = "0.0.0"\nedition.workspace = true\n')
    (tree / "vendor/crossterm-0.29.0/Cargo.toml").write_text('[package]\nname = "crossterm"\nversion = "0.29.0"\n')
    # A stale copy under target/ (or vendor/) is never a member: counting it would fail the lock check.
    (tree / "target/debug/Cargo.toml").write_text('[package]\nname = "ghost"\nversion.workspace = true\n')
    return tree


# --- the rule --------------------------------------------------------------------

@pytest.mark.parametrize("build_id, version", [
    ("v0.1.0", "0.1.0"),
    ("v0.1.0+zeroclaw.c473221313", "0.1.0"),
    ("v0.1.0-rc.1+zeroclaw.c473221313", "0.1.0-rc.1"),
    ("v12.3.4", "12.3.4"),
    (" v0.1.0\n", "0.1.0"),
    (f"v{UP}+zeroclaw.c473221313", UP),             # the dev default names upstream's own version
    ("main", None),                                   # workflow_dispatch on a branch
    ("dev-abcdef12+zeroclaw.c473221313", None),       # release.yml's id for a dispatch run
    ("0.1.0", None),
    ("v0.1", None),
    ("v0.1.0 dirty", None),
])
def test_the_build_id_names_the_release_version(build_id, version):
    assert sv.version_from_build_id(build_id) == version


# --- the rewrite -----------------------------------------------------------------

def test_stamping_rewrites_the_workspace_and_leaves_registry_packages_alone(tmp_path):
    tree = make_tree(tmp_path)
    before = (tree / "Cargo.lock").read_text()
    done = sv.stamp(tree, "0.1.0", UP)
    assert done == {"version": "0.1.0", "upstream": UP, "package": 1, "requirements": 2, "lock": 3}

    manifest = tomllib.loads((tree / "Cargo.toml").read_text())
    assert manifest["workspace"]["package"]["version"] == "0.1.0"
    deps = manifest["workspace"]["dependencies"]
    assert deps["caelza-api"] == {"path": "crates/caelza-api", "version": "0.1.0"}
    assert deps["caelza-config"] == {"path": "crates/caelza-config", "version": "0.1.0", "default-features": False}
    assert deps["rand"] == UP and deps["crossbeam-deque"]["version"] == UP, "registry requirements sharing the number stay"
    assert deps["serde"]["version"] == "1.0.200"
    assert manifest["package"] == {"name": "caelza", "version": {"workspace": True}, "edition": {"workspace": True}}

    after = (tree / "Cargo.lock").read_text()
    entries = dict(re.findall(r'\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"', after))
    assert entries == {"caelza": "0.1.0", "caelza-api": "0.1.0", "caelza-config": "0.1.0",
                       "crossbeam-deque": UP, "rand": UP, "rand_core": "0.6.4",
                       "crossterm": "0.29.0", "tool-fixture": "0.0.0"}
    # Only the three members' version lines moved: same checksums, same dependency lists.
    changed = [l for l in difflib.unified_diff(before.splitlines(), after.splitlines(), lineterm="", n=0)
               if l[:1] in "+-" and not l.startswith(("---", "+++"))]
    assert changed == [f'-version = "{UP}"', '+version = "0.1.0"'] * 3


def test_the_dev_default_and_a_versionless_build_id_leave_the_tree_as_upstream_has_it(tmp_path, capsys):
    tree = make_tree(tmp_path)
    for build_id in (f"v{UP}+zeroclaw.c473221313", "main", "dev-abcdef12+zeroclaw.c473221313"):
        assert sv.main([str(tree), build_id, UP]) == 0
        assert f"crates stay at upstream's {UP}" in capsys.readouterr().out
    assert (tree / "Cargo.toml").read_text() == MANIFEST
    assert (tree / "Cargo.lock").read_text() == LOCK


def test_the_cli_stamps_once_and_refuses_a_tree_that_is_not_upstream_at_that_version(tmp_path):
    tree = make_tree(tmp_path)

    def run(*args):
        return subprocess.run([sys.executable, "-I", str(SCRIPT), *args], capture_output=True, text=True)

    out = run(str(tree), "v0.1.0+zeroclaw.c473221313", UP)
    assert out.returncode == 0, out.stderr
    assert out.stdout.strip() == (f"version 0.1.0 stamped over upstream's {UP}: Cargo.toml (the workspace version, "
                                  "2 path requirements), Cargo.lock (3 members)")
    # build.sh restages from upstream on every run, so a second stamp never happens there; it still fails loudly.
    again = run(str(tree), "v0.2.0", UP)
    assert again.returncode == 1
    assert f'expected one [workspace.package] version = "{UP}", found 0' in again.stderr
    assert run(str(tmp_path / "nowhere"), "v0.1.0", UP).returncode == 1
    assert run(str(tree)).returncode == 2


def test_the_lock_must_carry_exactly_the_workspace_members(tmp_path):
    tree = make_tree(tmp_path / "a")
    lock = (tree / "Cargo.lock").read_text()
    gone = lock.replace(f'[[package]]\nname = "caelza-config"\nversion = "{UP}"\ndependencies = [\n "serde",\n]\n\n', "")
    assert gone != lock
    (tree / "Cargo.lock").write_text(gone)
    with pytest.raises(sv.StampError, match=r"members not in the lock: \['caelza-config'\]"):
        sv.stamp(tree, "0.1.0", UP)
    assert (tree / "Cargo.toml").read_text() == MANIFEST, "nothing is written when the check fails"

    tree = make_tree(tmp_path / "b")
    (tree / "Cargo.lock").write_text(LOCK + f'\n[[package]]\nname = "stray"\nversion = "{UP}"\n')
    with pytest.raises(sv.StampError, match=r"in the lock only: \['stray'\]"):
        sv.stamp(tree, "0.1.0", UP)


# --- the wiring ------------------------------------------------------------------

def test_build_sh_stamps_after_the_patches_and_before_cargo():
    build = (REPO_ROOT / "runtime" / "build.sh").read_text()
    assert 'export CAELZA_BUILD_ID="${CAELZA_BUILD_ID:-v${UP_VERSION}+zeroclaw.${UP_SHA:0:10}}"' in build
    assert 'python3 "$HERE/lib/stamp_version.py" "$WORK" "$CAELZA_BUILD_ID" "$UP_VERSION"' in build
    assert "for tool in git perl tar cargo python3; do" in build
    steps = re.search(r"\nfetch_upstream\n(.*?)\nbuild\n", build, re.S).group(1).split("\n")
    assert steps.index("apply_patches") < steps.index("stamp_version") < steps.index("write_notice")
    assert "| Crate version |" in build and "| Build id |" in build, "UPSTREAM.md records both numbers"


def test_release_yml_sets_the_build_id_before_staging_and_names_the_asset_after_the_tag():
    release = (REPO_ROOT / ".github" / "workflows" / "release.yml").read_text()
    assert 'tags: ["v*"]' in release
    job = release[release.index("\n  build:\n"):release.index("\n  release:\n")]
    assert ('if [ "$GITHUB_REF_TYPE" = tag ]; then ver="${GITHUB_REF_NAME#v}"; id="$GITHUB_REF_NAME"; '
            'else ver="dev-${GITHUB_SHA::8}"; id="$ver"; fi') in job
    assert 'echo "CAELZA_BUILD_ID=${id}+zeroclaw.${up::10}" >> "$GITHUB_ENV"' in job
    assert job.index("CAELZA_BUILD_ID=") < job.index("./runtime/build.sh --no-build") < job.index("cargo build --release --locked")
    assert 'ver="${{ steps.version.outputs.ver }}"' in job and 'name="caelza-${ver}-${{ matrix.target }}"' in job
    assert "CAELZA_BUILD_ID: ${{ github.ref_name }}" not in release, "the id is composed once, in the version step"


def test_the_manifest_names_the_version_the_next_tag_carries():
    data = tomllib.loads((REPO_ROOT / "bundle" / "manifest.toml").read_text())
    version = data["caelza"]["version"]
    assert sv.version_from_build_id(f"v{version}") == version
    upstream = tomllib.loads((REPO_ROOT / "runtime" / "upstream.toml").read_text())
    assert data["components"]["runtime"]["upstream_version"] == upstream["version"]


# --- the installers' side --------------------------------------------------------

class _Answer:
    returncode = 0

    def __init__(self, line: str):
        self.stdout = line + "\n"


def test_the_installers_accept_what_a_stamped_release_build_reports():
    """Tag → asset name → the version the guards expect; tag → build id → the
    version the crates carry → what `caelza --version` answers. One number."""
    tag, commit = "v0.1.0", "c473221313341a853e04122f93bb9bd26b5e6c47"
    ver, build_id = tag[1:], f"{tag}+zeroclaw.{commit[:10]}"          # release.yml's version step
    asset = f"caelza-{ver}-{TARGET}.tar.gz"
    release = rg.parse_release({"tag_name": tag, "assets": [{"name": asset, "url": "api://a"},
                                                             {"name": asset + ".sha256", "url": "api://s"}]}, TARGET)
    assert release.version == "0.1.0"

    stamped = sv.version_from_build_id(build_id)                        # build.sh's stamp
    answer = f"caelza {stamped} ({build_id})"                           # caelza-buildinfo: "<crate version> (<build id>)"
    assert rg.version_of("caelza", run=lambda *a, **k: _Answer(answer)) == "0.1.0"
    assert "0.1.0".split("+")[0] == release.version.split("+")[0]      # the probe's rule, runtime_guard.probe
    kt = (REPO_ROOT / "android/app/src/main/java/tech/enlightenedrepublic/caelza/runtime/ReleaseInstaller.kt").read_text()
    assert re.match(r"^caelza\s+(\d+\.\d+\.\d+\S*)", answer).group(1) == "0.1.0"   # ProcessProber.VERSION
    assert "version.substringBefore('+') != expectVersion.substringBefore('+')" in kt

    # Without the stamp the binary answers upstream's version and both probes refuse the release.
    unstamped = rg.version_of("caelza", run=lambda *a, **k: _Answer(f"caelza {UP} ({build_id})"))
    assert unstamped == UP and unstamped != release.version
